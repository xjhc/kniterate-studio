/**
 * Regenerates `src/knitout/passes/customist-rib-beanie-crown.ts` from
 * `reference/2x2-rib-beanie.kc`: the crown decreases and top jersey, as
 * offsets from the piece's left needle. Carriage-only moves and carrier
 * kickbacks are left to the converter.
 *
 *   node --import tsx scripts/extract-rib-beanie-crown.ts
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { parseKCodeDocument } from '../src/knitout/kcode/parser.js'
import { projectKCodeMachineTrace } from '../src/knitout/kcode/machine-trace.js'
import { KNITERATE_7GG_KCODE_PROFILE_V2 as profile } from '../src/knitout/kcode/machine-profile.js'

const REFERENCE = resolve(import.meta.dirname, '../reference/2x2-rib-beanie.kc')
const OUTPUT = resolve(import.meta.dirname, '../src/knitout/passes/customist-rib-beanie-crown.ts')
/** Piece's left KCode column and the pass range of the crown and top jersey. */
const LEFT_COLUMN = 29
const FIRST_PASS = 218
const LAST_PASS = 521

/** Renders the crown data module from the reference KCode text. */
export function renderRibBeanieCrownModule(source: string): string {
  const parsed = parseKCodeDocument(source, { profile, dialect: 'knitout-vendor', strict: true })
  if (!parsed.ok) throw new Error('reference is not strict KCode')
  const trace = projectKCodeMachineTrace(parsed.document, profile)

  type Step =
    | ['x', number, 'f' | 'b', number, number, number, number[]]
    | ['k', '+' | '-', number, number, number, number, number[], number[]]

  const steps: Step[] = []
  for (const pass of trace.passes.slice(FIRST_PASS, LAST_PASS + 1)) {
    const xfers = pass.actions.filter((action): action is Extract<typeof action, { kind: 'xfer' }> => action.kind === 'xfer')
    const knits = pass.actions.filter((action): action is Extract<typeof action, { at: unknown }> => action.kind === 'knit')
    if (xfers.length > 0) {
      const from = xfers[0]!.source.bed === 'front' ? 'f' : 'b'
      const stitches = new Set(xfers.map((action) => action.source.stitchSelector.encodedValue))
      if (stitches.size !== 1 || xfers.some((action) => (action.source.bed === 'front' ? 'f' : 'b') !== from)) throw new Error(`pass ${pass.index}: mixed transfer beds or stitch values`)
      const offsets = xfers.map((action) => action.source.kcodeColumn - LEFT_COLUMN)
      const last = steps.at(-1)
      // The converter splits one transfer batch into a rightward and a leftward pass; merge them back.
      if (last?.[0] === 'x' && last[1] === pass.rack && last[2] === from && last[3] === pass.speed && last[4] === pass.roller) last[6].push(...offsets)
      else steps.push(['x', pass.rack, from, pass.speed, pass.roller, [...stitches][0]!, offsets])
    } else if (knits.length > 0) {
      if (pass.carrier === '0') throw new Error(`pass ${pass.index}: knit without a carrier`)
      const front = knits.filter((action) => action.at.bed === 'front')
      const rear = knits.filter((action) => action.at.bed === 'rear')
      const value = (list: typeof knits) => {
        const values = new Set(list.map((action) => action.at.stitchSelector.encodedValue))
        if (values.size > 1) throw new Error(`pass ${pass.index}: mixed stitch values on one bed`)
        return values.size === 0 ? 0 : [...values][0]!
      }
      steps.push(['k', pass.direction === '>>' ? '+' : '-', pass.speed, pass.roller, value(front), value(rear),
        front.map((action) => action.at.kcodeColumn - LEFT_COLUMN).sort((a, b) => a - b),
        rear.map((action) => action.at.kcodeColumn - LEFT_COLUMN).sort((a, b) => a - b)])
    }
}

const body = steps.map((step) => `  ${JSON.stringify(step)},`).join('\n')
return `/**
 * GENERATED by scripts/extract-rib-beanie-crown.ts from reference/2x2-rib-beanie.kc
 * (passes ${FIRST_PASS}-${LAST_PASS}): the crown of Customist's 2×2 rib beanie and its top
 * jersey, as offsets from the piece's left needle, for the reference width of
 * 194 needles. Do not edit by hand.
 *
 *   ['x', rack, fromBed, speed, roller, xferStitch, sourceOffsets]
 *   ['k', direction, speed, roller, frontStitch, rearStitch, frontOffsets, rearOffsets]
 */

export type CustomistRibCrownStep =
  | readonly ['x', number, 'f' | 'b', number, number, number, readonly number[]]
  | readonly ['k', '+' | '-', number, number, number, number, readonly number[], readonly number[]]

export const CUSTOMIST_RIB_CROWN_WIDTH = 194

export const CUSTOMIST_RIB_CROWN_194_V1: readonly CustomistRibCrownStep[] = [
${body}
]
`
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  writeFileSync(OUTPUT, renderRibBeanieCrownModule(readFileSync(REFERENCE, 'utf8')))
  console.log(`wrote ${OUTPUT}`)
}
